export type PosCopyKey = keyof typeof en;
export type PosCopy = Record<PosCopyKey, string>;

const dictionaries: Record<"en" | "lo", PosCopy> = { en, lo };

function resolvePosLocale(locale?: string | null): "en" | "lo" {
  if (locale) {
    return normalizeLocale(locale);
  }
  if (typeof document !== "undefined") {
    return normalizeLocale(document.documentElement.dataset.locale);
  }
  return "en";
}

export function getPosCopy(locale?: string | null): PosCopy {
  return dictionaries[resolvePosLocale(locale)];
}

export function tPos(key: string, locale?: string | null) {
  const copy = getPosCopy(locale);
  if (key in copy) {
    return copy[key as PosCopyKey];
  }
  return en[key as PosCopyKey] ?? key;
}

export function fillPosCopy(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function posCopyKeyParity() {
  const enKeys = Object.keys(en).sort();
  const loKeys = Object.keys(lo).sort();
  return enKeys.length === loKeys.length && enKeys.every((key, index) => key === loKeys[index]);
}

export function posCopyHasNoReplacementChars() {
  return !Object.values(lo).some((value) => value.includes("?") && value.includes("??"));
}

export function posCopyKeepsCssClass() {
  return en["ui.text.ffd700"] === "text-[#FFD700]" && lo["ui.text.ffd700"] === "text-[#FFD700]";
}
