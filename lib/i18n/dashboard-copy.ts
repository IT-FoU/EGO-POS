const dashboardCopy = { en, lo };

export type DashboardCopy = typeof en;

export function getDashboardCopy(locale?: string | null): DashboardCopy {
  return locale === "lo" ? dashboardCopy.lo : dashboardCopy.en;
}

export function dashboardCopyKeyParity() {
  const enKeys = Object.keys(en).sort();
  const loKeys = Object.keys(lo).sort();
  return enKeys.length === loKeys.length && enKeys.every((key, index) => key === loKeys[index]);
}
