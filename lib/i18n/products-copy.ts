export type ProductsCopyKey = keyof typeof en;
export type ProductsCopy = Record<ProductsCopyKey, string>;

const dictionaries: Record<"en" | "lo", ProductsCopy> = { en, lo: lo as ProductsCopy };

function resolveProductsLocale(locale?: string | null): "en" | "lo" {
  if (locale) {
    return normalizeLocale(locale);
  }
  if (typeof document !== "undefined") {
    return normalizeLocale(document.documentElement.dataset.locale);
  }
  return "en";
}

export function getProductsCopy(locale?: string | null): ProductsCopy {
  return dictionaries[resolveProductsLocale(locale)];
}

export function tProducts(key: string, locale?: string | null) {
  const copy = getProductsCopy(locale);
  if (key in copy) {
    return copy[key as ProductsCopyKey];
  }
  return en[key as ProductsCopyKey] ?? key;
}

export function fillProductsCopy(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function productsCopyKeyParity() {
  const enKeys = Object.keys(en).sort();
  const loKeys = Object.keys(lo).sort();
  return enKeys.length === loKeys.length && enKeys.every((key, index) => key === loKeys[index]);
}

export function productsCopyHasNoReplacementChars() {
  return !Object.values(lo).some((value) => value.includes("?") && value.includes("??"));
}

export function productsCopyKeepsMimeAccept() {
  return en.acceptImages === lo.acceptImages && en.acceptImages.startsWith("image/");
}

