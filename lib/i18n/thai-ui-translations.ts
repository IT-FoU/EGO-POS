export function translateToThai(value: string) {
  const trimmed = value.trim();
  if (!trimmed || technicalTerms.has(trimmed)) {
    return value;
  }

  const exact = thaiUiTranslations[trimmed];
  if (exact) {
    return value.replace(trimmed, exact);
  }

  return value;
}
