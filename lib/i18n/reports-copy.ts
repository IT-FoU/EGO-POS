export type ReportsCopyKey = keyof typeof en;
export type ReportsCopy = Record<ReportsCopyKey, string>;

const dictionaries: Record<"en" | "lo", ReportsCopy> = { en, lo: lo as ReportsCopy };
export const REPORTS_COPY = dictionaries;

function resolveReportsLocale(locale?: string | null): "en" | "lo" {
  if (locale) return normalizeLocale(locale);
  if (typeof document !== "undefined") return normalizeLocale(document.documentElement.dataset.locale);
  return "en";
}

export function getReportsCopy(locale?: string | null): ReportsCopy {
  return dictionaries[resolveReportsLocale(locale)];
}

export function tReports(key: string, locale?: string | null) {
  const copy = getReportsCopy(locale);
  if (key in copy) return copy[key as ReportsCopyKey];
  return en[key as ReportsCopyKey] ?? key;
}

export function fillReportsCopy(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function reportsCopyKeyParity() {
  const enKeys = Object.keys(en).sort();
  const loKeys = Object.keys(lo).sort();
  return enKeys.length === loKeys.length && enKeys.every((key, index) => key === loKeys[index]);
}

export function reportsCopyHasNoReplacementChars() {
  return !Object.values(lo).some((value) => value.includes("\uFFFD"));
}

export function datePresetLabel(preset: string, locale?: string | null) {
  if (preset === "all") return tReports("allTime", locale);
  if (preset === "custom") return tReports("custom", locale);
  if (preset === "this_month") return tReports("thisMonth", locale);
  if (preset === "this_week") return tReports("thisWeek", locale);
  if (preset === "today") return tReports("today", locale);
  if (preset === "yesterday") return tReports("yesterday", locale);
  return preset;
}

export function paymentMethodLabel(method: string, locale?: string | null) {
  const value = method.toLowerCase();
  if (value === "card" || value === "visa") return tReports("paymentCard", locale);
  if (value === "transfer") return tReports("paymentTransfer", locale);
  if (value === "qr") return tReports("paymentQr", locale);
  if (value === "cash") return tReports("paymentCash", locale);
  return method;
}

const reportLabelMap: Record<string, ReportsCopyKey> = Object.fromEntries(
  (Object.keys(en) as ReportsCopyKey[])
    .filter((key) => !en[key].includes("{"))
    .map((key) => [en[key], key]),
);

const reportLabelMapLower: Record<string, ReportsCopyKey> = Object.fromEntries(
  Object.entries(reportLabelMap).map(([label, key]) => [label.toLowerCase(), key]),
);

export function localizeReportLabel(label: string, locale?: string | null) {
  const week = label.match(/^Week\s+(\d+)$/i);
  if (week) return fillReportsCopy(tReports("weekNumber", locale), { n: week[1] });
  const key = reportLabelMap[label] ?? reportLabelMapLower[label.toLowerCase()];
  return key ? tReports(key, locale) : label;
}

