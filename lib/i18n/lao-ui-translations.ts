export function translateToLao(value: string) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const trimmed = value.trim();
  if (!trimmed || approvedTechnicalTerms.has(trimmed)) {
    return value;
  }

  const exact = extraLaoUiTranslations[trimmed] ?? laoUiTranslations[trimmed];
  if (exact) {
    return `${leading}${exact}${trailing}`;
  }

  const colon = trimmed.match(/^(.+?)([:：])$/);
  if (colon) {
    const translated = extraLaoUiTranslations[colon[1]] ?? laoUiTranslations[colon[1]];
    if (translated) {
      return `${leading}${translated}${colon[2]}${trailing}`;
    }
  }

  const dynamicColon = trimmed.match(/^(.+?)([:：])\s+(.+)$/);
  if (dynamicColon) {
    const translated = extraLaoUiTranslations[dynamicColon[1]] ?? laoUiTranslations[dynamicColon[1]];
    if (translated) {
      return `${leading}${translated}${dynamicColon[2]} ${dynamicColon[3]}${trailing}`;
    }
  }

  return value;
}
