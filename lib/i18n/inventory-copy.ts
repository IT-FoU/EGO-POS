export type InventoryCopyKey = keyof typeof en;
export type InventoryCopy = Record<InventoryCopyKey, string>;

const dictionaries: Record<"en" | "lo", InventoryCopy> = { en, lo: lo as InventoryCopy };

function resolveInventoryLocale(locale?: string | null): "en" | "lo" {
  if (locale) {
    return normalizeLocale(locale);
  }
  if (typeof document !== "undefined") {
    return normalizeLocale(document.documentElement.dataset.locale);
  }
  return "en";
}

export function getInventoryCopy(locale?: string | null): InventoryCopy {
  return dictionaries[resolveInventoryLocale(locale)];
}

export function tInventory(key: string, locale?: string | null) {
  const copy = getInventoryCopy(locale);
  if (key in copy) {
    return copy[key as InventoryCopyKey];
  }
  return en[key as InventoryCopyKey] ?? key;
}

export function fillInventoryCopy(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function inventoryCopyKeyParity() {
  const enKeys = Object.keys(en).sort();
  const loKeys = Object.keys(lo).sort();
  return enKeys.length === loKeys.length && enKeys.every((key, index) => key === loKeys[index]);
}

export function inventoryCopyHasNoReplacementChars() {
  return !Object.values(lo).some((value) => value.includes("?") && value.includes("??"));
}

export function inventoryCopyKeepsMimeAccept() {
  return en.acceptImages === lo.acceptImages && en.acceptImages.startsWith("image/");
}

