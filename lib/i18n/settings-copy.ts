export type SettingsCopyKey = keyof typeof en;
export type SettingsCopy = Record<SettingsCopyKey, string>;

const dictionaries: Record<"en" | "lo", SettingsCopy> = { en, lo: lo as SettingsCopy };
export const SETTINGS_COPY = dictionaries;

function resolveSettingsLocale(locale?: string | null): "en" | "lo" {
  if (locale) return normalizeLocale(locale);
  if (typeof document !== "undefined") return normalizeLocale(document.documentElement.dataset.locale);
  return "en";
}

export function getSettingsCopy(locale?: string | null): SettingsCopy {
  return dictionaries[resolveSettingsLocale(locale)];
}

export function tSettings(key: string, locale?: string | null) {
  const copy = getSettingsCopy(locale);
  if (key in copy) return copy[key as SettingsCopyKey];
  return en[key as SettingsCopyKey] ?? key;
}

export function fillSettingsCopy(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function settingsCopyKeyParity() {
  const enKeys = Object.keys(en).sort();
  const loKeys = Object.keys(lo).sort();
  return enKeys.length === loKeys.length && enKeys.every((key, index) => key === loKeys[index]);
}

export function settingsCopyHasNoReplacementChars() {
  return !Object.values(lo).some((value) => value.includes("\uFFFD"));
}

