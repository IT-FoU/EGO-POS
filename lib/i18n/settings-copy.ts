export function localizeSettingsError(error?: string | null, locale?: string | null) {
  if (!error) return tSettings("failedToLoad", locale);
  if (error.startsWith("Permission denied")) return tSettings("permissionDenied", locale);
  const exact = knownErrors[error];
  if (exact) return tSettings(exact, locale);
  return error;
}

