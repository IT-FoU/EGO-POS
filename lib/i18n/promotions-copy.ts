export type PromotionsCopyKey = keyof typeof en;
export type PromotionsCopy = Record<PromotionsCopyKey, string>;

const dictionaries: Record<"en" | "lo", PromotionsCopy> = { en, lo: lo as PromotionsCopy };
export const PROMOTIONS_COPY = dictionaries;

function resolvePromotionsLocale(locale?: string | null): "en" | "lo" {
  if (locale) return normalizeLocale(locale);
  if (typeof document !== "undefined") return normalizeLocale(document.documentElement.dataset.locale);
  return "en";
}

export function getPromotionsCopy(locale?: string | null): PromotionsCopy {
  return dictionaries[resolvePromotionsLocale(locale)];
}

export function tPromotions(key: string, locale?: string | null) {
  const copy = getPromotionsCopy(locale);
  if (key in copy) return copy[key as PromotionsCopyKey];
  return en[key as PromotionsCopyKey] ?? key;
}

export function fillPromotionsCopy(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function promotionsCopyKeyParity() {
  const enKeys = Object.keys(en).sort();
  const loKeys = Object.keys(lo).sort();
  return enKeys.length === loKeys.length && enKeys.every((key, index) => key === loKeys[index]);
}

export function promotionsCopyHasNoReplacementChars() {
  return !Object.values(lo).some((value) => value.includes("\uFFFD"));
}

