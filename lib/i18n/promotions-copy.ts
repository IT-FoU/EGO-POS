const promotionStatusCopyKeys: Record<string, PromotionsCopyKey> = {
  active: "active",
  approved: "approved",
  archived: "archived",
  draft: "draft",
  expired: "expired",
  inactive: "inactive",
  pending_approval: "pendingApproval",
  "pending approval": "pendingApproval",
  rejected: "rejected",
  scheduled: "scheduled",
};

export function promotionStatusLabel(status: string, locale?: string | null) {
  const normalized = status.trim().toLowerCase().replaceAll(" ", "_");
  const key = promotionStatusCopyKeys[normalized] ?? promotionStatusCopyKeys[status];
  if (key) return tPromotions(key, locale);
  return status.replaceAll("_", " ");
}

export function promotionTypeLabel(type: string, locale?: string | null) {
  if (type === "percentage") return tPromotions("percentageDiscount", locale);
  if (type === "fixed_amount") return tPromotions("fixedAmount", locale);
  if (type === "buy_x_get_y") return tPromotions("buyXGetY", locale);
  if (type === "combo_set") return tPromotions("comboSet", locale);
  if (type === "member_discount") return tPromotions("memberDiscount", locale);
  return type;
}

export function promotionRiskLabel(level: string, locale?: string | null) {
  if (level === "High") return tPromotions("riskHigh", locale);
  if (level === "Medium") return tPromotions("riskMedium", locale);
  if (level === "Low") return tPromotions("riskLow", locale);
  return level;
}

