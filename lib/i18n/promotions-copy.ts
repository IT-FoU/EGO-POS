export type PromotionsCopyKey = keyof typeof en;
export type PromotionsCopy = Record<PromotionsCopyKey, string>;

const dictionaries: Record<"en" | "lo", PromotionsCopy> = { en, lo: lo as PromotionsCopy };
export const PROMOTIONS_COPY = dictionaries;

function resolvePromotionsLocale(locale?: string | null): "en" | "lo" {
  if (locale) return normalizeLocale(locale);
  if (typeof document !== "undefined") return normalizeLocale(document.documentElement.dataset.locale);
  return "en";
}

export function getPromotionsCopy(locale?: string | null): PromotionsCopy {
  return dictionaries[resolvePromotionsLocale(locale)];
}

export function tPromotions(key: string, locale?: string | null) {
  const copy = getPromotionsCopy(locale);
  if (key in copy) return copy[key as PromotionsCopyKey];
  return en[key as PromotionsCopyKey] ?? key;
}

export function fillPromotionsCopy(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

export function promotionsCopyKeyParity() {
  const enKeys = Object.keys(en).sort();
  const loKeys = Object.keys(lo).sort();
  return enKeys.length === loKeys.length && enKeys.every((key, index) => key === loKeys[index]);
}

export function promotionsCopyHasNoReplacementChars() {
  return !Object.values(lo).some((value) => value.includes("\uFFFD"));
}

export function promotionStatusLabel(status: string, locale?: string | null) {
  if (status === "active") return tPromotions("active", locale);
  if (status === "inactive") return tPromotions("inactive", locale);
  if (status === "scheduled") return tPromotions("scheduled", locale);
  if (status === "expired") return tPromotions("expired", locale);
  if (status === "draft") return tPromotions("draft", locale);
  if (status === "archived") return tPromotions("archived", locale);
  return status.replaceAll("_", " ");
}

export function promotionTypeLabel(type: string, locale?: string | null) {
  if (type === "percentage") return tPromotions("percentageDiscount", locale);
  if (type === "fixed_amount") return tPromotions("fixedAmount", locale);
  if (type === "buy_x_get_y") return tPromotions("buyXGetY", locale);
  if (type === "combo_set") return tPromotions("comboSet", locale);
  if (type === "member_discount") return tPromotions("memberDiscount", locale);
  return type;
}

const knownErrors: Record<string, PromotionsCopyKey> = {
  "Missing promotion name.": "missingName",
  "Missing promotion type.": "missingType",
  "Missing discount value.": "missingDiscountValue",
  "Missing target.": "missingTarget",
  "Missing date.": "missingDate",
  "Coupon missing code.": "couponMissingCode",
  "Promotion update failed.": "saveFailed",
  "Promotion archive failed.": "archiveFailed",
  "Promotion save failed.": "saveFailed",
  "Duplicate promotion failed.": "duplicateFailed",
};

export function localizePromotionError(error?: string | null, locale?: string | null) {
  if (!error) return tPromotions("failedToLoad", locale);
  if (error.startsWith("Permission denied")) return tPromotions("permissionDenied", locale);
  if (error.startsWith("Approval required") || error.includes("approval required")) return tPromotions("approvalRequired", locale);
  const exact = knownErrors[error];
  if (exact) return tPromotions(exact, locale);
  return error;
}

